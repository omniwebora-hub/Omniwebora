import { z } from "zod";
import { LIMITS, budgetOptions, serviceOptions, situationOptions, timelineOptions } from "./options";

const values = <T extends readonly { value: string }[]>(opts: T) =>
  opts.map((o) => o.value) as unknown as [T[number]["value"], ...T[number]["value"][]];

const attr = z.string().trim().max(LIMITS.attr.max).optional();

export const inquirySchema = z.object({
  name: z
    .string({ error: "Enter your name." })
    .trim()
    .min(LIMITS.name.min, { error: "Enter your name." })
    .max(LIMITS.name.max, { error: `Keep your name under ${LIMITS.name.max} characters.` }),
  email: z
    .string({ error: "Enter your business email." })
    .trim()
    .max(LIMITS.email.max, { error: "That email address is too long." })
    .pipe(z.email({ error: "Enter an email address like name@company.com." })),
  company: z
    .string()
    .trim()
    .max(LIMITS.company.max, { error: `Keep the company name under ${LIMITS.company.max} characters.` })
    .optional()
    .default(""),
  service: z.enum(values(serviceOptions), { error: "Choose a service, or Not sure yet." }).default("not-sure"),
  message: z
    .string({ error: "Tell us a little about the project." })
    .trim()
    .min(LIMITS.message.min, { error: `Add a little more detail (at least ${LIMITS.message.min} characters).` })
    .max(LIMITS.message.max, { error: `Keep the description under ${LIMITS.message.max} characters.` }),
  situation: z.enum(values(situationOptions)).optional(),
  timeline: z.enum(values(timelineOptions)).optional(),
  budget: z.enum(values(budgetOptions)).optional(),
  /** Structured summary generated by the brief studio (what the visitor chose), attached to the email. */
  brief: z.string().trim().max(LIMITS.brief.max).optional(),
  consent: z.literal(true, { error: "Agree to the privacy notice so we can reply." }),
  /** Honeypot: must stay empty. */
  website: z.string().max(0).optional().default(""),
  startedAt: z.number().int().positive(),
  page: z.string().trim().max(LIMITS.attr.max).optional(),
  attribution: z
    .object({
      utm_source: attr,
      utm_medium: attr,
      utm_campaign: attr,
      utm_term: attr,
      utm_content: attr,
      referrer: attr,
      landing: attr,
    })
    .partial()
    .optional(),
});

export type Inquiry = z.infer<typeof inquirySchema>;

export type InquiryFieldErrors = Partial<Record<keyof Inquiry, string>>;

export function fieldErrors(error: z.ZodError): InquiryFieldErrors {
  const out: InquiryFieldErrors = {};
  for (const issue of error.issues) {
    const key = issue.path[0] as keyof Inquiry | undefined;
    if (key && !out[key]) out[key] = issue.message;
  }
  return out;
}
