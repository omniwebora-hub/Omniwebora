"""Track the crystal through the Home push-in clip so the Omniwebora mark stays locked to its core.

Scale: template matching frame by frame from the crystal's verified rest pose (H01_TRACK[0]), smoothed
and kept monotone (the camera only pushes in). Position: the centre of the crystal's dark core,
segmented every few frames and fitted with a smooth cubic (the template drifts as the crystal turns
toward the camera). The mark keeps its tuned offset from the core, scaled with the push.
Writes src/content/homePushTrack.ts: one [x, y, h] sample per video frame (plate fractions; h is the
crystal height used as the mark's scale reference).

Usage: FFMPEG=/path/to/ffmpeg python scripts/cinematic/track_crystal.py
"""
import json, os, subprocess, tempfile, glob
import numpy as np, cv2
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CLIP = os.path.join(ROOT, "public/assets/cinematic/home-push/v1600.mp4")
OUT = os.path.join(ROOT, "src/content/homePushTrack.ts")
REST = (0.7307, 0.5272, 0.2843)  # x, y, h on the first frame (measured on the H00 still)

tmp = tempfile.mkdtemp()
subprocess.run([os.environ.get("FFMPEG", "ffmpeg"), "-v", "error", "-i", CLIP, "-vf", "scale=800:-1", f"{tmp}/f%03d.png"], check=True)
imgs = [cv2.imread(f) for f in sorted(glob.glob(f"{tmp}/f*.png"))]
H, W = imgs[0].shape[:2]
cx, cy, ch = REST
tw, th = 0.16 * W, 0.40 * H  # the core and the inner glass
tmpl = imgs[0][int(cy * H - th / 2): int(cy * H + th / 2), int(cx * W - tw / 2): int(cx * W + tw / 2)]
track, s, px, py = [[cx, cy, ch]], 1.0, cx * W, cy * H
for im in imgs[1:]:
    best = None
    for sc in np.arange(max(1.0, s - 0.03), s + 0.045, 0.005):
        t = cv2.resize(tmpl, None, fx=sc, fy=sc, interpolation=cv2.INTER_LINEAR)
        hh, ww = t.shape[:2]
        x0, y0 = int(max(0, px - ww / 2 - 40)), int(max(0, py - hh / 2 - 40))
        reg = im[y0: int(min(H, py + hh / 2 + 40)), x0: int(min(W, px + ww / 2 + 40))]
        if reg.shape[0] < hh or reg.shape[1] < ww:
            continue
        r = cv2.matchTemplate(reg, t, cv2.TM_CCOEFF_NORMED)
        _, mv, _, ml = cv2.minMaxLoc(r)
        if best is None or mv > best[0]:
            best = (mv, sc, x0 + ml[0] + ww / 2, y0 + ml[1] + hh / 2)
    _, s, px, py = best
    track.append([px / W, py / H, ch * s])
a = np.array(track, dtype=float)
for j in range(3):
    a[:, j] = np.convolve(np.pad(a[:, j], 3, mode="edge"), np.ones(7) / 7, mode="valid")
a[:, 2] = np.maximum.accumulate(a[:, 2])


def core_centre(im):
    """Centre of the dark navy core (bounding box of the largest dark-blue region)."""
    b, g, r = (im[..., k].astype(int) for k in range(3))
    m = ((r + g + b) / 3 < 85) & (b > r + 25) & (b > g + 5)
    m[:, : int(W * 0.3)] = False
    m[: int(H * 0.08), :] = False
    m[int(H * 0.85):, :] = False
    m = ndimage.binary_closing(ndimage.binary_opening(m, iterations=1), iterations=4)
    lab, n = ndimage.label(m)
    k = int(np.argmax(ndimage.sum(m, lab, range(1, n + 1)))) + 1
    ys, xs = np.nonzero(lab == k)
    return (xs.min() + xs.max()) / 2 / W, (ys.min() + ys.max()) / 2 / H


keys = list(range(0, len(imgs), 6)) + [len(imgs) - 1]
pts = np.array([core_centre(imgs[i]) for i in keys])
idx = np.arange(len(imgs))
core = np.stack([np.polyval(np.polyfit(keys, pts[:, j], 3), idx) for j in range(2)], axis=1)
s = a[:, 2] / a[0, 2]
off = np.array(REST[:2]) - core[0]  # the mark's tuned offset from the core at rest
a[:, 0] = core[:, 0] + off[0] * s
a[:, 1] = core[:, 1] + off[1] * s
rows = ", ".join(f"[{x:.4f}, {y:.4f}, {h:.4f}]" for x, y, h in a)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/cinematic/track_crystal.py: do not edit by hand.\n")
    f.write("/** The crystal in each frame of home-push (x, y, height as plate fractions). */\n")
    f.write(f"export const HOME_PUSH_TRACK: readonly (readonly [number, number, number])[] = [{rows}];\n")
print(len(track), "frames ->", OUT)
